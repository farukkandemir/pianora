// Inlines the OSMD bundle into viewer.html and emits a TS module exporting
// the result as a string, so the WebView needs no network or asset plumbing.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const osmd = readFileSync(join(root, 'node_modules/opensheetmusicdisplay/build/opensheetmusicdisplay.min.js'), 'utf8');
const html = readFileSync(join(root, 'src/sheet/viewer.html'), 'utf8')
  .replace('<!--OSMD-->', () => `<script>${osmd}</script>`);
const out = `// Generated by scripts/build-sheet-html.mjs. Do not edit.\nexport const SHEET_VIEWER_HTML = ${JSON.stringify(html)};\n`;
writeFileSync(join(root, 'src/sheet/viewerHtml.generated.ts'), out);
console.log(`wrote src/sheet/viewerHtml.generated.ts (${(out.length / 1024).toFixed(0)} KB)`);
